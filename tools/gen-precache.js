#!/usr/bin/env node
/* Generate dev/js/precache-list.js by walking the app tree.
 *
 * v1's list was maintained by hand, and the README told users to remember to
 * edit it whenever they added an asset. A hand-kept manifest of files that must
 * be cached for the app to work offline is a footgun: the day it drifts, the
 * app half-loads in a car with no signal. This runs in CI before deploy, so the
 * list is always exactly what is on disk.
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..', 'dev');
const OUT = path.join(ROOT, 'js', 'precache-list.js');

// The worker itself and the generated list are never precached: the browser
// fetches sw.js on its own update check, and precaching it would pin an old
// worker in place.
const SKIP_FILES = new Set(['sw.js', 'precache-list.js']);
const SKIP_EXT = new Set(['.md']);

function walk(dir, out = []) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))) {
    if (entry.name.startsWith('.')) continue;
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) walk(full, out);
    else if (!SKIP_FILES.has(entry.name) && !SKIP_EXT.has(path.extname(entry.name))) {
      out.push('./' + path.relative(ROOT, full).split(path.sep).join('/'));
    }
  }
  return out;
}

const files = walk(ROOT);
// './' is the URL the home-screen icon actually opens; without it the very
// first offline navigation misses.
const list = ['./', ...files];

fs.writeFileSync(OUT, `/* GENERATED by tools/gen-precache.js — do not edit by hand. */
self.PRECACHE_LIST = ${JSON.stringify(list, null, 2)};
`);

console.log(`precache-list.js: ${list.length} entries`);
